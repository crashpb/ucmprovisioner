<?php
/**
 * CiscoCnfGenerator — builds SIP<MAC>.cnf (+ SIPDefault.cnf body) for legacy
 * Cisco 7940/7960 phones (plain-text .cnf family, NOT USECALLMANAGER XML).
 *
 * BLF buttons map to speed_lineN / speed_labelN. Asterisk subscribe= is still
 * required (phones do not send SUBSCRIBE). Remote reload uses check-sync NOTIFY
 * plus a syncinfo.xml token bump. See docs/DEVICE-SUPPORT.md.
 *
 * @package FreePBX\modules\Ucmprovisioner
 */

namespace FreePBX\modules\Ucmprovisioner;

require_once __DIR__ . '/MediaUrl.php';

class CiscoCnfGenerator
{
    /**
     * @param array $ctx resolvePhone() output
     * @return array{filename:?string,content:string,sip_default:string,warnings:array}
     */
    public function generate(array $ctx): array
    {
        $phone    = $ctx['phone'];
        $settings = $ctx['settings'];
        $lines    = $ctx['lines'];
        $warnings = [];

        $mac = strtoupper(preg_replace('/[^0-9A-F]/i', '', (string) ($phone['mac'] ?? '')));
        $filename = ($mac !== '' && strlen($mac) === 12) ? "SIP{$mac}.cnf" : null;
        if ($filename === null) {
            $warnings[] = 'No valid MAC; cannot determine SIP<MAC>.cnf filename.';
        }

        $ext = (string) ($phone['extension'] ?? '');
        $secret = $this->secret($lines);
        if (strlen($secret) > 16) {
            throw new \RuntimeException('The live PBX secret exceeds the Cisco 7940/7960 16-character limit. Change the PBX secret first; truncating only the phone config would guarantee an authentication mismatch.');
        }
        $label = isset($phone['label']) ? (string)$phone['label'] : $ext;
        $primaryLine = [];
        foreach ($lines as $candidate) {
            if ((int)($candidate['featureId'] ?? 0) === 9
                && (int)($candidate['lineIndex'] ?? 1) === 1) {
                $primaryLine = $candidate;
                break;
            }
        }
        $lineLabel = (string)($primaryLine['label'] ?? $label);
        $callerDisplay = (string)($primaryLine['displayName'] ?? $label);

        // Cisco's SIP IP Phone Administrator Guide publishes an 11-character
        // phone_label maximum for 7940/7960. Clip only this final device field;
        // the independently rendered line-key and caller labels remain intact.
        $phoneLabel = $this->ascii($label, 'phone label');
        if (strlen($phoneLabel) > 11) {
            $warnings[] = "Label \"$label\" exceeds the Cisco 7940/7960 11-character phone_label limit and was emitted as \"" . substr($phoneLabel, 0, 11) . "\". The line-key and caller labels remain separate.";
            $phoneLabel = substr($phoneLabel, 0, 11);
        }

        $out = [];
        $out[] = '# SIP Configuration - generated by ucmprovisioner';
        $out[] = '';
        $out[] = '# Line 1 appearance';
        $out[] = 'line1_name: ' . $this->q($ext, 'extension', true);
        $out[] = 'line1_authname: ' . $this->q($ext, 'extension', true);
        $out[] = 'line1_password: ' . $this->q($secret, 'SIP secret', true);
        $out[] = 'line1_displayname: ' . $this->qLatin1($callerDisplay, 'caller display name', $warnings);
        $out[] = 'line1_shortname: ' . $this->qLatin1(
            $this->lineKeyLabel($lineLabel, 1, $warnings),
            'line 1 key label',
            $warnings
        );
        $out[] = '';
        $out[] = 'phone_label: ' . $this->q($phoneLabel, 'phone label');
        $prompt = $this->ascii((string)($settings['phone_prompt'] ?? $ext), 'phone prompt');
        if (strlen($prompt) > 15) {
            $warnings[] = 'phone_prompt exceeds the Cisco 7940/7960 15-character limit and was truncated.';
            $prompt = substr($prompt, 0, 15);
        }
        $phonePassword = (string)($settings['phone_password'] ?? '');
        if (strlen($phonePassword) > 31) {
            throw new \RuntimeException('phone_password exceeds the Cisco 7940/7960 31-character console/Telnet limit.');
        }
        $telnetLevel = max(0, min(2, (int)($settings['telnet_level'] ?? 0)));
        $out[] = 'phone_prompt: ' . $this->q($prompt, 'phone prompt');
        if ($phonePassword !== '') {
            $out[] = 'phone_password: ' . $this->q($phonePassword, 'phone password', true);
        }
        $out[] = "telnet_level: \"{$telnetLevel}\"";
        $firmware = trim((string)($settings['firmware'] ?? ''));
        if ($firmware !== '') {
            // Firmware is a per-phone template choice. Putting it in SIPDefault.cnf made
            // mixed templates race: the last generated phone silently selected the load
            // for the whole site's legacy fleet.
            $out[] = 'image_version: ' . $this->q($firmware, 'firmware load', true);
        }
        $pbx = (string)($settings['pbx_addr'] ?? '');
        $logoUrl = $this->legacyLogoUrl($settings, $pbx, $warnings);
        if ($logoUrl !== '') {
            $out[] = 'logo_url: ' . $this->q($logoUrl, 'logo URL', true);
        }
        // 7940/7960 firmware does not reliably parse query strings. Prefer the
        // tokenized PATH_INFO endpoint even when the modern XML query URL also
        // exists in the shared site settings.
        $directoryUrl = (string)($settings['cisco_legacy_directory_url']
            ?? ($settings['cisco_directory_url'] ?? ($settings['directory_url'] ?? '')));
        // An omitted directive inherits SIPDefault.cnf (or the handset cache).
        // Emit Cisco's empty-string value when the resolved phonebook is None.
        $out[] = 'directory_url: ' . $this->q(str_replace('{{pbx_ip}}', $pbx, $directoryUrl), 'directory URL', true);
        $servicesUrl = (string)($settings['cisco_services_url'] ?? '');
        if ($servicesUrl !== '') {
            $out[] = 'services_url: ' . $this->q(str_replace('{{pbx_ip}}', $pbx, $servicesUrl), 'services URL', true);
        }
        $out[] = '';

        $lineKeys = (int) (($ctx['model']['line_keys'] ?? null) ?: 6);
        $usedKeys = [1 => true];

        foreach ($lines as $ln) {
            $btn = (int) ($ln['button'] ?? 0);
            if ($btn < 2 || $btn > $lineKeys) {
                continue;
            }
            
            $fid = (int) ($ln['featureId'] ?? 0);
            
            if ($fid === 9) {
                // Secondary extension (line)
                $ext = (string) ($ln['name'] ?? '');
                if ($ext === '') continue;
                $lbl = (string) ($ln['label'] ?? $ext);
                $displayName = (string)($ln['displayName'] ?? $lbl);
                $sec = (string) ($ln['secret'] ?? '');
                
                if (strlen($sec) > 16) { throw new \RuntimeException("Line $btn SIP secret exceeds the Cisco 7940/7960 16-character limit"); }
                $out[] = "line{$btn}_name: " . $this->q($ext, "line $btn extension", true);
                $out[] = "line{$btn}_authname: " . $this->q($ext, "line $btn extension", true);
                $out[] = "line{$btn}_password: " . $this->q($sec, "line $btn SIP secret", true);
                $out[] = "line{$btn}_displayname: " . $this->qLatin1($displayName, "line $btn caller display name", $warnings);
                $out[] = "line{$btn}_shortname: " . $this->qLatin1(
                    $this->lineKeyLabel($lbl, $btn, $warnings),
                    "line $btn key label",
                    $warnings
                );
                
                $usedKeys[$btn] = true;
            } elseif (in_array($fid, [2, 21, 22], true)) {
                // Speed dial / BLF
                $target = (string) ($ln['speedDialNumber'] ?? '');
                if ($target === '') continue;
                $lbl = (string) ($ln['label'] ?? $target);
                
                $out[] = "speed_line{$btn}: " . $this->q($target, "speed dial $btn target", true);
                $out[] = "speed_label{$btn}: " . $this->q($lbl, "speed dial $btn label");
                
                // Clear the SIP line registry for this button since it's a speed dial
                $out[] = "line{$btn}_name: \"\"";
                $out[] = "line{$btn}_authname: \"\"";
                $out[] = "line{$btn}_password: \"\"";
                $out[] = "line{$btn}_displayname: \"\"";
                $out[] = "line{$btn}_shortname: \"UNPROVISIONED\"";
                
                $usedKeys[$btn] = true;
            }
        }

        // Clear unused/cached line registrations (buttons 2..N) to prevent flash cache conflicts
        for ($i = 2; $i <= $lineKeys; $i++) {
            if (!isset($usedKeys[$i])) {
                $out[] = "line{$i}_name: \"\"";
                $out[] = "line{$i}_authname: \"\"";
                $out[] = "line{$i}_password: \"\"";
                $out[] = "line{$i}_displayname: \"\"";
                $out[] = "line{$i}_shortname: \"UNPROVISIONED\"";
            }
        }
        $out[] = '';

        $sipDefault = $this->buildSipDefault($settings);

        return [
            'filename'    => $filename,
            'content'     => $this->serialize($out),
            'sip_default' => $sipDefault,
            'warnings'    => $warnings,
        ];
    }

    /** Site-global SIPDefault.cnf content (managed as a whole file on TFTP). */
    public function buildSipDefault(array $settings, array &$warnings = [], bool $includePhoneDefaults = true): string
    {
        $pbx     = (string) ($settings['pbx_addr'] ?? '');
        $port    = (string) ($settings['sip_port'] ?? '5060');
        $fw      = trim((string)($settings['cisco_legacy_site_firmware'] ?? ''));
        $sync    = (string) ($settings['legacy_sync_token'] ?? '1');
        $ntp     = (string) ($settings['ntp_server'] ?? '');
        $tz      = (string) ($settings['cisco_legacy_timezone'] ?? ($settings['timezone'] ?? 'IT'));
        $vm      = (string) ($settings['voicemail_number'] ?? '*97');

        $lines = [
            '# SIP Default Configuration - generated by ucmprovisioner',
            '',
            'proxy1_address: ' . $this->q($pbx, 'PBX address', true),
            'proxy1_port: ' . $this->q($port, 'SIP port', true),
            'proxy_register: "1"',
            'timer_register_expires: "3600"',
            '',
            'preferred_codec: "g711ulaw"',
            'dtmf_outofband: "avt"',
            'dtmf_avt_payload: "101"',
            '',
            'messages_uri: ' . $this->q($vm, 'voicemail number', true),
            'tftp_cfg_dir: "./"',
            '',
            'sntp_mode: "unicast"',
        ];
        if ($fw !== '') {
            array_splice($lines, 2, 0, ['image_version: ' . $this->q($fw, 'site firmware load', true), '']);
        }
        if ($ntp !== '') {
            $lines[] = 'sntp_server: ' . $this->q($ntp, 'NTP server', true);
        }
        $lines[] = 'time_zone: ' . $this->q($tz, 'time zone', true);
        $dstAdjust = !array_key_exists('cisco_legacy_dst_auto_adjust', $settings) || !empty($settings['cisco_legacy_dst_auto_adjust']);
        $lines[] = 'dst_auto_adjust: "' . ($dstAdjust ? '1' : '0') . '"';
        $lines[] = '';
        $lines[] = 'sync: ' . $this->q($sync, 'sync token', true);

        // These remaining defaults also exist in SIP<MAC>.cnf. A phone's logo
        // or directory can override them without changing the shared policy.
        if (!$includePhoneDefaults) { return $this->serialize($lines); }

        // logo_url — per Cisco's official SIP IP Phone Administrator Guide (Appendix D):
        // requires a fully-qualified HTTP URL (NOT a TFTP-relative path), Windows 256-color
        // .bmp, 90x56px (phone displays at ~2-bit depth regardless), 5-15KB recommended.
        // "CMXML PhoneImage objects are not supported for this parameter" — i.e. this is a
        // completely different mechanism from the newer XML phones' Desktops/List.xml.
        $logoUrl = $this->legacyLogoUrl($settings, $pbx, $warnings);
        if ($logoUrl !== '') {
            $logoUrl = str_replace('{{pbx_ip}}', $pbx, $logoUrl);
            if (stripos($logoUrl, 'http://') !== 0 && stripos($logoUrl, 'https://') !== 0) {
                $warnings[] = "logo_url ('$logoUrl') must be a full http(s):// URL — Cisco 7940/7960 firmware does not accept a TFTP-relative path for logo_url. Skipped.";
            } else {
                $lines[] = '';
                $lines[] = 'logo_url: ' . $this->q($logoUrl, 'logo URL', true);
            }
        }
        $directoryUrl = (string)($settings['cisco_legacy_directory_url']
            ?? ($settings['cisco_directory_url'] ?? ($settings['directory_url'] ?? '')));
        if ($directoryUrl !== '') {
            $directoryUrl = str_replace('{{pbx_ip}}', $pbx, $directoryUrl);
            $lines[] = 'directory_url: ' . $this->q($directoryUrl, 'directory URL', true);
        }
        // The managed route contains a phone identity and belongs only in
        // SIP<MAC>.cnf; a site-global value can point every phone at one MAC.
        $lines[] = '';

        return $this->serialize($lines);
    }

    /** syncinfo.xml body for remote reboot/reload of 7940/7960 fleet. */
    public static function syncInfoXml(string $syncToken, string $imageVersion = '*'): string
    {
        return "<SYNCINFO>\n   <IMAGE VERSION=\"{$imageVersion}\" SYNC=\"{$syncToken}\"/>\n</SYNCINFO>\n";
    }

    private function secret(array $lines): string
    {
        foreach ($lines as $ln) {
            if ((int) ($ln['featureId'] ?? 0) === 9 && !empty($ln['secret'])) {
                return (string) $ln['secret'];
            }
        }
        return '';
    }

    /** P0S3 firmware expects a direct, plain-HTTP Windows BMP resource. */
    private function legacyLogoUrl(array $settings, string $pbx, array &$warnings): string
    {
        $url = MediaUrl::repairLegacyCiscoAssetUrl(
            trim((string)($settings['hosted_image_url'] ?? ($settings['legacy_logo_url'] ?? '')))
        );
        if ($url === '') { return ''; }
        $url = str_replace('{{pbx_ip}}', $pbx, $url);
        $parts = parse_url($url);
        if (filter_var($url, FILTER_VALIDATE_URL) === false
            || !is_array($parts)
            || strtolower((string)($parts['scheme'] ?? '')) !== 'http'
            || trim((string)($parts['host'] ?? '')) === ''
            || isset($parts['user'])
            || isset($parts['pass'])
            || isset($parts['query'])
            || isset($parts['fragment'])
            || !preg_match('/\.bmp$/iD', (string)($parts['path'] ?? ''))
        ) {
            $warnings[] = "logo_url ('$url') must be a direct plain-http:// BMP URL without credentials, a query string, or a fragment. Skipped.";
            return '';
        }
        return $url;
    }

    /** Quote one legacy-CNF scalar without allowing a value to create directives. */
    private function q($value, string $field, bool $strict = false): string
    {
        $value = $this->ascii((string)$value, $field, $strict);
        if (preg_match('/[\x00-\x1F\x7F]/', $value)) {
            throw new \InvalidArgumentException("$field contains a control character that Cisco CNF cannot represent safely");
        }
        if (str_contains($value, '"')) {
            if ($strict) { throw new \InvalidArgumentException("$field contains a quote that Cisco CNF cannot represent safely"); }
            $value = str_replace('"', "'", $value);
        }
        return '"' . $value . '"';
    }

    /** Keep non-display directives in a deterministic 7-bit subset. */
    private function ascii(string $value, string $field, bool $strict = false): string
    {
        if (!preg_match('/[^\x20-\x7E]/', $value)) {
            return $value;
        }
        if (preg_match('/[\x00-\x1F\x7F]/', $value)) {
            throw new \InvalidArgumentException("$field contains a control character that Cisco CNF cannot represent safely");
        }
        if ($strict) {
            throw new \InvalidArgumentException("$field contains a non-ASCII character that Cisco 7940/7960 CNF cannot represent safely");
        }
        // Windows iconv represents some accents with an apostrophe ("é" -> "e'")
        // while glibc iconv does not. Protect real apostrophes, remove only those
        // introduced by transliteration, and keep generated CNF deterministic.
        $apostropheMarker = 'UCMPAPOSTROPHE';
        while (str_contains($value, $apostropheMarker)) {
            $apostropheMarker .= 'X';
        }
        $protected = str_replace("'", $apostropheMarker, $value);
        $ascii = @iconv('UTF-8', 'ASCII//TRANSLIT//IGNORE', $protected);
        if ($ascii === false) {
            $ascii = preg_replace('/[^\x20-\x7E]/', '?', $value);
        } else {
            $ascii = str_replace("'", '', $ascii);
            $ascii = str_replace($apostropheMarker, "'", $ascii);
        }
        return (string)$ascii;
    }

    /**
     * Cisco 7940/7960 lineX_shortname and lineX_displayname support
     * ISO-8859-1. Preserve representable accents; transliterate only values
     * which Latin-1 cannot encode.
     */
    private function qLatin1(string $value, string $field, array &$warnings): string
    {
        if (preg_match('/[\x00-\x1F\x7F]/', $value)) {
            throw new \InvalidArgumentException("$field contains a control character that Cisco CNF cannot represent safely");
        }
        if (str_contains($value, '"')) {
            $value = str_replace('"', "'", $value);
        }
        $latin1 = @iconv('UTF-8', 'ISO-8859-1//TRANSLIT', $value);
        if ($latin1 === false) {
            $latin1 = $this->ascii($value, $field);
            $warnings[] = "$field could not be encoded as ISO-8859-1 and was transliterated to the module's 7-bit fallback.";
        } else {
            $roundTrip = @iconv('ISO-8859-1', 'UTF-8', $latin1);
            if ($roundTrip === false || $roundTrip !== $value) {
                $warnings[] = "$field contains characters outside ISO-8859-1 and was transliterated for Cisco 7940/7960 firmware.";
            }
        }
        return '"' . $latin1 . '"';
    }

    /**
     * Cisco documents lineX_shortname as the line-key label but publishes no
     * numeric maximum. Keep a 30-character module policy; the LCD may clip it
     * sooner depending on glyph width and firmware.
     */
    private function lineKeyLabel(string $value, int $line, array &$warnings): string
    {
        if ($this->characterLength($value) <= 30) {
            return $value;
        }
        $clipped = function_exists('mb_substr')
            ? mb_substr($value, 0, 30, 'UTF-8')
            : $this->unicodeSlice($value, 30);
        $warnings[] = sprintf(
            'Cisco 7940/7960 line%d_shortname exceeds the module 30-character safety policy and was emitted as "%s"; Cisco publishes no numeric hardware limit and the LCD may clip sooner.',
            $line,
            $clipped
        );
        return $clipped;
    }

    private function characterLength(string $value): int
    {
        if (function_exists('mb_strlen')) {
            return mb_strlen($value, 'UTF-8');
        }
        $count = preg_match_all('/./us', $value, $matches);
        return $count === false ? strlen($value) : $count;
    }

    private function unicodeSlice(string $value, int $maxChars): string
    {
        $matched = preg_match_all('/./us', $value, $matches);
        return $matched === false
            ? substr($value, 0, $maxChars)
            : implode('', array_slice($matches[0], 0, $maxChars));
    }

    /** CRLF is accepted by every documented legacy load and avoids editor/transfer ambiguity. */
    private function serialize(array $lines): string
    {
        return implode("\r\n", $lines) . "\r\n";
    }

}
