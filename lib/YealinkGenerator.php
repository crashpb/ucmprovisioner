<?php
/**
 * YealinkGenerator — builds <MAC>.cfg provisioning files.
 *
 * Yealink phones subscribe for BLF natively and do not need Cisco Asterisk glue.
 * Supported remote reloads use the vendor check-sync SIP NOTIFY event. See
 * docs/DEVICE-SUPPORT.md.
 *
 * @package FreePBX\modules\Ucmprovisioner
 */

namespace FreePBX\modules\Ucmprovisioner;

class YealinkGenerator
{
    /** `linekey.N.type` values emitted by this generator. */
    private const KEY_BLF = 16;
    private const KEY_SPEEDDIAL = 13;

    /**
     * @param array $ctx resolvePhone() output
     * @return array{filename:?string,content:string,warnings:array}
     */
    public function generate(array $ctx): array
    {
        $phone    = $ctx['phone'] ?? [];
        $settings = $ctx['settings'] ?? [];
        $lines    = $ctx['lines'] ?? [];
        $model    = $ctx['model'] ?? [];
        $warnings = [];
        $modelName = strtoupper((string)($model['model'] ?? ''));
        $role = strtolower((string)($model['role'] ?? ''));
        if ($this->unsupportedRole($role, $modelName)) {
            $message = sprintf(
                'Yealink %s is a %s and is provisioned through its DECT system, not with a desk-phone MAC cfg.',
                $modelName !== '' ? $modelName : 'endpoint',
                $role !== '' ? $role : 'handset/system component'
            );
            return ['filename'=>null, 'content'=>'', 'warnings'=>[$message], 'error'=>$message];
        }
        $isDectBase = str_contains($role, 'base')
            || (string)($model['config_profile'] ?? '') === 'yealink_dect_single'
            || in_array($modelName, ['W60B', 'W70B'], true);

        $mac = strtolower(preg_replace('/[^0-9a-f]/i', '', (string) ($phone['mac'] ?? '')));
        $filename = ($mac !== '' && strlen($mac) === 12) ? "{$mac}.cfg" : null;
        if ($filename === null) {
            $warnings[] = 'No valid MAC; cannot determine Yealink cfg filename.';
        }

        $pbx    = (string) ($settings['pbx_addr'] ?? '');
        $port   = (string) ($settings['sip_port'] ?? '5060');
        $transport = $this->transportCode((string)($settings['transport'] ?? 'udp'));
        $vm     = $this->value((string) ($settings['voicemail_number'] ?? '*97'));
        $ntp    = $this->value((string) ($settings['ntp_server'] ?? $pbx));
        $tz     = $this->value((string) ($settings['yealink_timezone'] ?? ($settings['timezone'] ?? '+3:30')));

        $out = [];
        $out[] = '#!version:1.0.0.1';
        $out[] = '## Generated by ucmprovisioner — do not edit on phone';
        $out[] = '';
        $out[] = 'sip.notify_reboot_enable = 1';
        $out[] = '';

        // Account registration is independent of physical DSS-key placement.
        $maxAccounts = (int)($model['sip_accounts'] ?? 0);
        $maxAccounts = $maxAccounts > 0 ? $maxAccounts : ($isDectBase ? 10 : 16);
        $maxHandsets = (int)($model['handsets_max'] ?? 0);
        $maxHandsets = $maxHandsets > 0 ? $maxHandsets : 8;
        $usedAccounts = [];
        $handsetLineLabels = [];
        $accountOffset = 0;
        foreach ($lines as $ln) {
            if ((int)($ln['featureId'] ?? 0) === 9) {
                $accountOffset++;
                $lIdx = (int)($ln['accountIndex'] ?? ($ln['lineIndex'] ?? $accountOffset));
                if ($lIdx < 1 || $lIdx > $maxAccounts || isset($usedAccounts[$lIdx])) {
                    $warnings[] = sprintf('Yealink account index %d is outside this model\'s 1-%d capacity or is duplicated; skipped.', $lIdx, $maxAccounts);
                    continue;
                }
                $usedAccounts[$lIdx] = true;
                $lExt = $this->value((string) ($ln['name'] ?? ''));
                $lAuth = $this->value((string) ($ln['authName'] ?? $lExt));
                $lLabel = $this->limited(
                    $this->value((string) ($ln['label'] ?? $lExt)),
                    99,
                    "Yealink account {$lIdx} label",
                    $warnings
                );
                $lDisplayName = $this->limited(
                    $this->value((string) ($ln['displayName'] ?? $lExt)),
                    99,
                    "Yealink account {$lIdx} display name",
                    $warnings
                );
                $lSecret = $this->value((string) ($ln['secret'] ?? ''));

                $out[] = "account.{$lIdx}.enable = 1";
                $out[] = "account.{$lIdx}.label = {$lLabel}";
                $out[] = "account.{$lIdx}.display_name = {$lDisplayName}";
                $out[] = "account.{$lIdx}.auth_name = {$lAuth}";
                $out[] = "account.{$lIdx}.password = {$lSecret}";
                $out[] = "account.{$lIdx}.user_name = {$lExt}";
                $out[] = "account.{$lIdx}.sip_server.1.address = {$this->value($pbx)}";
                $out[] = "account.{$lIdx}.sip_server.1.port = {$this->value($port)}";
                $out[] = "account.{$lIdx}.transport = {$transport}";
                $out[] = "voice_mail.number.{$lIdx} = {$vm}";
                $out[] = "account.{$lIdx}.subscribe_mwi = 1";
                $out[] = "account.{$lIdx}.subscribe_mwi_to_vm = 1";
                $out[] = '';
                if ($isDectBase) {
                    $assigned = (string)($settings["yl_dect_account_{$lIdx}_handsets"] ?? $lIdx);
                    foreach (array_unique(array_filter(array_map('intval', preg_split('/\s*,\s*/', $assigned)))) as $handset) {
                        if ($handset >= 1 && $handset <= $maxHandsets) {
                            $out[] = "account.{$lIdx}.handset.{$handset}.enable = 1";
                            $handsetLineLabels[$handset][$lIdx] = $lLabel;
                        } else {
                            $warnings[] = sprintf('Yealink DECT handset %d is outside this base\'s 1-%d capacity; skipped.', $handset, $maxHandsets);
                        }
                    }
                    $out[] = '';
                }
            }
        }

        if ($ntp !== '') {
            $out[] = "local_time.ntp_server1 = {$ntp}";
        }
        if ($tz !== '') {
            $out[] = "local_time.time_zone = {$tz}";
        }

        if (!empty($settings['hosted_image_url'])) {
            $logoUrl = str_replace('{{pbx_ip}}', $pbx, $settings['hosted_image_url']);
            $wallpaper = (string)($settings['yealink_wallpaper_file'] ?? '');
            if ($wallpaper === '') {
                $query = [];
                parse_str((string)(parse_url($logoUrl, PHP_URL_QUERY) ?: ''), $query);
                $wallpaper = (string)($query['file'] ?? basename(parse_url($logoUrl, PHP_URL_PATH) ?: ''));
            }
            $out[] = "wallpaper_upload.url = {$this->value($logoUrl)}";
            if ($wallpaper !== '') {
                $out[] = "phone_setting.backgrounds = {$this->value($wallpaper)}";
            }
        }
        if (!empty($settings['admin_password'])) {
            $out[] = "security.user_name.admin = admin";
            $out[] = 'security.user_password = admin:' . $this->value((string)$settings['admin_password']);
        }
        if (!empty($settings['user_password'])) {
            $out[] = "security.user_name.user = user";
            $out[] = 'security.user_password = user:' . $this->value((string)$settings['user_password']);
        }
        if (empty($settings['static.firmware.url'])) {
            $firmwareUrl = '';
            foreach (['firmware_bundle_url', 'yealink_firmware_url', '_managed_firmware_url'] as $key) {
                if (trim((string)($settings[$key] ?? '')) !== '') {
                    $firmwareUrl = trim((string)$settings[$key]);
                    break;
                }
            }
            if ($firmwareUrl !== '') {
                $out[] = 'static.firmware.url = ' . $this->value($firmwareUrl);
            }
        }
        if ($isDectBase) {
            foreach ($this->dectHandsetNames($settings, $handsetLineLabels, $maxHandsets, 24, $warnings, 'Yealink') as $handset => $name) {
                $out[] = "handset.{$handset}.name = {$name}";
            }
            $out[] = '';
        }
        $phonebookUrl = $this->value((string)($settings['yealink_phonebook_url'] ?? ($settings['phonebook_url'] ?? '')));
        if ($phonebookUrl !== '') {
            $out[] = "remote_phonebook.data.1.url = {$phonebookUrl}";
            $out[] = "remote_phonebook.data.1.name = Directory";
        }
        if (isset($settings['auto_answer']) && $settings['auto_answer'] !== '') {
            $out[] = 'features.intercom.allow = ' . $this->value((string)$settings['auto_answer']);
        }

        // Dump native Yealink dot-separated settings from UI or JSON
        foreach ($settings as $k => $v) {
            if (preg_match('/^[a-zA-Z0-9_.]+$/', (string)$k) && strpos($k, '.') !== false) {
                if ($this->isManagedIdentityKey((string)$k)) {
                    $warnings[] = "Advanced Yealink setting '$k' was ignored because AD/template identity owns that field.";
                    continue;
                }
                if (preg_match('/\Aaccount\.\d+\.(?:enable|user_name|auth_name|password|transport|sip_server\.1\.(?:address|port))\z/D', (string)$k)) {
                    $warnings[] = "Advanced Yealink setting '$k' was ignored because the managed account owns that field.";
                    continue;
                }
                // Handset policy is delivered by a DECT base. Emitting these keys to a T-series
                // desk phone is misleading at best and firmware-dependent at worst.
                if (!$isDectBase && $this->isHandsetPolicyKey((string)$k)) {
                    continue;
                }
                if ($v === 'custom' && !empty($settings['hosted_ringtone_url'])) {
                    $v = str_replace('{{pbx_ip}}', $pbx, $settings['hosted_ringtone_url']);
                }
                $out[] = "{$k} = {$this->value((string)$v)}";
            }
        }

        // Yealink Digit timeout and Dial pattern
        if (isset($settings['digit_timeout'])) {
            $out[] = "dialplan.digitmap.interdigit_long = " . (int)$settings['digit_timeout'];
        }
        if (!empty($settings['dial_pattern'])) {
            $out[] = "dialplan.digitmap.active = 1";
            $out[] = 'dialplan.digitmap.string = ' . $this->value((string)$settings['dial_pattern']);
        }
        $out[] = '';

        // Configure physical linekeys
        $modelKeys = (int)($model['programmable_keys'] ?? 0);
        $baseKeys = max(0, $modelKeys > 0 ? $modelKeys : (int)($settings['_base_line_keys'] ?? ($model['line_keys'] ?? 1)));
        $expansionTypes = $model['expansion_types'] ?? [];
        if (is_string($expansionTypes)) {
            $expansionTypes = json_decode($expansionTypes, true) ?: preg_split('/\s*,\s*/', $expansionTypes);
        }
        $supportsExpansion = !empty($model['kem_support'])
            || !empty($expansionTypes)
            || (int)($model['max_expansion_modules'] ?? 0) > 0;
        $keysPerExpansion = (int)($model['keys_per_expansion'] ?? 0);
        if ($keysPerExpansion < 1) {
            $legacyFortyKeyTypes = ['EXP20', 'EXP39', 'EXP40'];
            $keysPerExpansion = array_intersect($legacyFortyKeyTypes, array_map('strtoupper', (array)$expansionTypes)) ? 40 : 60;
        }
        $maxExpansionModules = (int)($model['max_expansion_modules'] ?? 0);
        if ($maxExpansionModules < 1 && $supportsExpansion) {
            $maxExpansionModules = $keysPerExpansion === 40 ? 6 : 3;
        }
        foreach ($isDectBase ? [] : $lines as $ln) {
            $btn = (int) ($ln['button'] ?? 0);
            $fid = (int) ($ln['featureId'] ?? 0);
            if ($btn < 1) {
                continue;
            }
            if ($fid === 9 && $btn > $baseKeys) {
                // The SIP account remains registered; it simply has no physical line appearance.
                continue;
            }
            if ($btn > $baseKeys && $supportsExpansion) {
                $offset = $btn - $baseKeys - 1;
                $module = intdiv($offset, $keysPerExpansion) + 1;
                $key = ($offset % $keysPerExpansion) + 1;
                if ($maxExpansionModules < 1 || $module > $maxExpansionModules) {
                    $warnings[] = sprintf('Yealink key position %d exceeds the configured expansion-module capacity; skipped.', $btn);
                    continue;
                }
                $target = $this->value((string)($ln['speedDialNumber'] ?? ''));
                if ($target === '') { continue; }
                $type = (is_numeric((string)($ln['feature'] ?? ''))) ? (int)$ln['feature'] : (($fid === 21 || $fid === 22) ? self::KEY_BLF : self::KEY_SPEEDDIAL);
                $out[] = "expansion_module.{$module}.key.{$key}.type = {$type}";
                $out[] = "expansion_module.{$module}.key.{$key}.line = 1";
                $out[] = "expansion_module.{$module}.key.{$key}.value = {$target}";
                $label = $this->limited(
                    $this->value((string)($ln['label'] ?? $target)),
                    99,
                    "Yealink expansion key {$module}.{$key} label",
                    $warnings
                );
                $out[] = "expansion_module.{$module}.key.{$key}.label = {$label}";
                $out[] = '';
            } elseif ($btn > $baseKeys) {
                $warnings[] = sprintf('Yealink key position %d exceeds this model\'s %d programmable keys; skipped.', $btn, $baseKeys);
            } elseif ($fid === 9) { // Line registration
                $lIdx = (int)($ln['accountIndex'] ?? ($ln['lineIndex'] ?? 1));
                $lbl = $this->limited(
                    $this->value((string)($ln['label'] ?? ($ln['name'] ?? ''))),
                    99,
                    "Yealink line key {$btn} label",
                    $warnings
                );
                $out[] = "linekey.{$btn}.type = 15";
                $out[] = "linekey.{$btn}.line = {$lIdx}";
                $out[] = "linekey.{$btn}.label = {$lbl}";
                $out[] = '';
            } else { // BLF / Speeddial / Other DSS Keys
                $target = $this->value((string) ($ln['speedDialNumber'] ?? ''));
                if ($target === '') {
                    continue;
                }
                $lbl = $this->limited(
                    $this->value((string)($ln['label'] ?? $target)),
                    99,
                    "Yealink DSS key {$btn} label",
                    $warnings
                );
                $featStr = (string) ($ln['feature'] ?? '');
                if (is_numeric($featStr)) {
                    $type = (int)$featStr;
                } else {
                    $type = ($fid === 21 || $fid === 22) ? self::KEY_BLF : self::KEY_SPEEDDIAL;
                }
                $out[] = "linekey.{$btn}.type = {$type}";
                $out[] = "linekey.{$btn}.line = 1";
                $out[] = "linekey.{$btn}.value = {$target}";
                $out[] = "linekey.{$btn}.label = {$lbl}";
                $out[] = '';
            }
        }

        return [
            'filename' => $filename,
            'content'  => implode("\n", $out) . "\n",
            'warnings' => $warnings,
        ];
    }

    private function transportCode(string $t): int
    {
        return match (strtolower($t)) {
            'tcp' => 1,
            'tls' => 2,
            default => 0, // UDP
        };
    }

    private function value(string $value): string
    {
        return trim(str_replace(["\r", "\n"], ' ', $value));
    }

    private function limited(string $value, int $maximum, string $field, array &$warnings): string
    {
        $characters = preg_split('//u', $value, -1, PREG_SPLIT_NO_EMPTY);
        if ($characters === false || count($characters) <= $maximum) {
            return $value;
        }
        $warnings[] = sprintf('%s exceeded the documented %d-character limit and was truncated.', $field, $maximum);
        return rtrim(implode('', array_slice($characters, 0, $maximum)));
    }

    /** @return array<int,string> */
    private function dectHandsetNames(
        array $settings,
        array $lineLabels,
        int $maximum,
        int $labelLimit,
        array &$warnings,
        string $vendor
    ): array {
        $inventory = $settings['dect_handsets'] ?? [];
        if (is_string($inventory)) {
            $inventory = json_decode($inventory, true) ?: [];
        }
        if (!is_array($inventory)) {
            return [];
        }
        $overrides = [];
        foreach ($inventory as $row) {
            if (!is_array($row)) {
                continue;
            }
            $slot = (int)($row['slot'] ?? 0);
            if ($slot < 1 || $slot > $maximum) {
                $warnings[] = sprintf('%s DECT handset slot %d is outside this base\'s 1-%d capacity; its name was skipped.', $vendor, $slot, $maximum);
                continue;
            }
            $name = $this->value((string)($row['label'] ?? ''));
            if ($name !== '') {
                $overrides[$slot] = $name;
            }
        }
        $names = [];
        for ($slot = 1; $slot <= $maximum; $slot++) {
            if (isset($overrides[$slot])) {
                $names[$slot] = $this->limited($overrides[$slot], $labelLimit, "{$vendor} DECT handset {$slot} name", $warnings);
                continue;
            }
            $sources = $lineLabels[$slot] ?? [];
            if (!$sources) {
                continue;
            }
            ksort($sources);
            $names[$slot] = $this->limited((string)reset($sources), $labelLimit, "{$vendor} DECT handset {$slot} name", $warnings);
            if (count($sources) > 1) {
                $warnings[] = sprintf(
                    '%s DECT handset %d has multiple assigned accounts; account %d supplied its derived name.',
                    $vendor,
                    $slot,
                    (int)array_key_first($sources)
                );
            }
        }
        return $names;
    }

    private function unsupportedRole(string $role, string $model): bool
    {
        return (bool)preg_match('/handset|radio|manager/', $role)
            || in_array($model, ['W71H', 'W73H', 'W56H', 'W80B', 'W90B', 'W90DM'], true);
    }

    private function isHandsetPolicyKey(string $key): bool
    {
        return str_starts_with($key, 'custom.handset.')
            || in_array($key, [
                'static.auto_provision.handset_configured.enable',
                'static.auto_provision.custom.handset.protect',
            ], true);
    }

    private function isManagedIdentityKey(string $key): bool
    {
        return preg_match('/^account\.\d+\.(?:label|display_name)$/', $key) === 1
            || preg_match('/^handset\.\d+\.name$/', $key) === 1;
    }

}
